"""
doc_writer.py
-------------
Formats matched job listings into a local .docx file using python-docx.

Behavior:
  - If OUTPUT_DOCX_PATH doesn't exist yet, creates a new document with a
    title page / header.
  - If it already exists, APPENDS a new dated run section to the bottom
    instead of overwriting — so repeated runs build a running log of
    matched jobs over time.
"""

import os
from datetime import datetime

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

HEADER_COLOR = RGBColor(0x1F, 0x4E, 0x79)  # dark blue
SCORE_COLOR = RGBColor(0x2E, 0x7D, 0x32)  # green


def _build_new_document() -> Document:
    doc = Document()

    title = doc.add_heading("Quaero — Matched Job Listings", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = subtitle.add_run(
        "Automatically generated by Quaero — do not edit headers manually"
    )
    run.italic = True
    run.font.size = Pt(9)

    return doc


def _add_run_header(doc: Document, run_count: int):
    """Adds a dated section separator each time the script runs."""
    doc.add_paragraph()  # spacer
    heading = doc.add_heading(
        f"Search run — {datetime.now().strftime('%Y-%m-%d %H:%M')}", level=1
    )
    heading.runs[0].font.color.rgb = HEADER_COLOR

    doc.add_paragraph(f"{run_count} matching job(s) found this run.")
    doc.add_paragraph("_" * 60)


def _add_job_entry(doc: Document, job: dict, rank: int):
    """Adds one formatted job listing block."""
    heading = doc.add_heading(f"{rank}. {job['title']}", level=2)
    heading.runs[0].font.color.rgb = HEADER_COLOR

    meta = doc.add_paragraph()
    meta.add_run("Company: ").bold = True
    meta.add_run(f"{job['company']}\n")
    meta.add_run("Location: ").bold = True
    meta.add_run(f"{job['location']}\n")
    meta.add_run("Work Type: ").bold = True
    meta.add_run(f"{job['job_type'].title()} · {job['work_mode'].title()}\n")
    if job.get("posted_date"):
        meta.add_run("Posted Date: ").bold = True
        meta.add_run(f"{job['posted_date'][:10]}\n")
    meta.add_run("Source: ").bold = True
    meta.add_run(f"{job['source']}")

    score_para = doc.add_paragraph()
    score_run = score_para.add_run(f"Match Score: {job['match_score']}/100")
    score_run.bold = True
    score_run.font.color.rgb = SCORE_COLOR

    summary_para = doc.add_paragraph()
    summary_para.add_run("Summary: ").bold = True
    summary_para.add_run(job["match_summary"])

    if job.get("url"):
        link_para = doc.add_paragraph()
        link_para.add_run("Apply: ").bold = True
        link_para.add_run(job["url"])

    doc.add_paragraph("-" * 40)


def write_jobs_to_docx(jobs: list, output_path: str) -> str:
    """
    Writes (or appends) matched jobs to a .docx file.
    Returns the absolute path of the file written, for confirmation/logging.
    """
    if os.path.exists(output_path):
        doc = Document(output_path)
    else:
        doc = _build_new_document()

    _add_run_header(doc, len(jobs))

    if not jobs:
        doc.add_paragraph("No jobs matched your criteria in this run.")
    else:
        for i, job in enumerate(jobs, start=1):
            _add_job_entry(doc, job, i)

    doc.save(output_path)
    return os.path.abspath(output_path)
