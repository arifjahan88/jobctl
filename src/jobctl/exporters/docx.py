"""Word (.docx) report exporter with clickable hyperlinks and jobctl branding."""

from __future__ import annotations

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.dml import MSO_THEME_COLOR_INDEX
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

from jobctl.models import ScoredJob

HEADER_COLOR = RGBColor(0x0F, 0x17, 0x2A)  # slate navy
ACCENT_COLOR = RGBColor(0x0D, 0x94, 0x88)  # teal
SCORE_COLOR = RGBColor(0x15, 0x80, 0x3D)  # emerald green


def _add_hyperlink(paragraph, text: str, url: str) -> None:
    """Add a real clickable hyperlink to a python-docx paragraph."""
    part = paragraph.part
    r_id = part.relate_to(
        url,
        "http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink",
        is_external=True,
    )
    hyperlink = OxmlElement("w:hyperlink")
    hyperlink.set(qn("r:id"), r_id)

    new_run = OxmlElement("w:r")
    r_pr = OxmlElement("w:rPr")

    color = OxmlElement("w:color")
    color.set(qn("w:val"), "0D9488")
    r_pr.append(color)

    underline = OxmlElement("w:u")
    underline.set(qn("w:val"), "single")
    r_pr.append(underline)

    new_run.append(r_pr)
    text_elem = OxmlElement("w:t")
    text_elem.text = text
    new_run.append(text_elem)
    hyperlink.append(new_run)

    paragraph._p.append(hyperlink)


def _build_document(now: datetime, count: int) -> Document:
    doc = Document()

    title = doc.add_heading("jobctl — Matched Engineering Jobs", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    if title.runs:
        title.runs[0].font.color.rgb = HEADER_COLOR

    subtitle = doc.add_paragraph()
    subtitle.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = subtitle.add_run(
        f"Generated by jobctl v2.0.0 on {now.strftime('%Y-%m-%d %H:%M')} · "
        f"{count} matching role(s) (Posted within previous 2 days)"
    )
    sub_run.italic = True
    sub_run.font.size = Pt(9.5)

    doc.add_paragraph("_" * 68)
    return doc


def _add_job_entry(doc: Document, item: ScoredJob, rank: int) -> None:
    badge = " [NEW]" if item.is_new else f" [SEEN x{item.times_seen}]"
    heading = doc.add_heading(f"{rank}. {item.title}{badge}", level=2)
    if heading.runs:
        heading.runs[0].font.color.rgb = HEADER_COLOR

    meta = doc.add_paragraph()
    meta.add_run("Company: ").bold = True
    meta.add_run(f"{item.company}\n")
    meta.add_run("Location: ").bold = True
    meta.add_run(f"{item.location}\n")
    meta.add_run("Work Type: ").bold = True
    meta.add_run(f"{item.job_type.title()} · {item.work_mode.title()}\n")
    if item.posted_date:
        meta.add_run("Posted Date: ").bold = True
        meta.add_run(f"{item.posted_date[:10]}\n")
    meta.add_run("Source: ").bold = True
    meta.add_run(item.source)

    b = item.score_breakdown
    score_para = doc.add_paragraph()
    score_run = score_para.add_run(
        f"Match Score: {item.match_score}/100  "
        f"(Skills: {b.skills_pct}% · Title: {b.title_pct}% · Type: {b.job_type_pct}%)"
    )
    score_run.bold = True
    score_run.font.color.rgb = SCORE_COLOR

    summary_para = doc.add_paragraph()
    summary_para.add_run("Matched Skills: ").bold = True
    summary_para.add_run(item.match_summary)

    if item.url:
        link_para = doc.add_paragraph()
        link_para.add_run("Apply: ").bold = True
        try:
            _add_hyperlink(link_para, item.url, item.url)
        except Exception:
            link_para.add_run(item.url)

    doc.add_paragraph("-" * 48)


def write_jobs_to_docx(
    jobs: list[ScoredJob],
    output_path: str | Path,
    now: datetime | None = None,
) -> Path:
    """Write matched jobs to a standalone .docx report file and return its Path."""
    target = Path(output_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    current = now or datetime.now()

    doc = _build_document(current, len(jobs))
    if not jobs:
        doc.add_paragraph("No jobs matched your criteria in this run.")
    else:
        for idx, item in enumerate(jobs, start=1):
            _add_job_entry(doc, item, idx)

    doc.save(str(target))
    return target.resolve()
